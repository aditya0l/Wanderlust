/* Self-hosted photos: every Unsplash photo the site uses is downloaded once and saved in assets/photos as WebP
   at a few widths, so pages load them from this site's own CDN instead of Unsplash. Run after adding or changing
   photos in data/site.js or index.html (needs curl, cwebp and sips, which are on macOS with `brew install webp`):

     node tools/build-photos.js

   Writes assets/photos/<photo-id>-<width>.webp, assets/photos/og-<photo-id>.jpg (1200 x 630, for link previews)
   and data/photos.js, the list the site reads (SiteData.img falls back to Unsplash for anything not listed). */
const fs = require("fs"), path = require("path"), { execFileSync } = require("child_process");
const ROOT = path.join(__dirname, ".."), OUT = path.join(ROOT, "assets/photos"), CACHE = path.join(__dirname, ".photo-cache");
const WIDTHS = [640, 1080, 1600];
const OG = "photo-1609601546193-f558f1ebb385";             // the link-preview photo (index.html og:image)
fs.mkdirSync(OUT, { recursive: true }); fs.mkdirSync(CACHE, { recursive: true });

// every photo id in the content, the homepage and the account page
const ids = new Set();
for (const f of ["data/site.js", "index.html", "account.html", "account.js"]) {
  const s = fs.readFileSync(path.join(ROOT, f), "utf8");
  (s.match(/photo-\d+-[0-9a-f]+/g) || []).forEach(id => ids.add(id));
}

const run = (cmd, args) => execFileSync(cmd, args, { stdio: ["ignore", "pipe", "pipe"] }).toString();
const { execFile } = require("child_process");
const fetchMaster = (id, attempt = 1) => new Promise((resolve, reject) => {   // one high-quality download per photo, kept outside the site
  const master = path.join(CACHE, id + ".jpg"), part = master + ".part";
  execFile("curl", ["-sSfL", "--max-time", "240", "-o", part, `https://images.unsplash.com/${id}?w=2000&q=90&fm=jpg&fit=max`], err => {
    if (!err) { fs.renameSync(part, master); return resolve(); }
    fs.rmSync(part, { force: true });                  // never keep a half-finished file
    attempt < 2 ? fetchMaster(id, attempt + 1).then(resolve, reject) : reject(new Error(`download failed: ${id}`));
  });
});

(async () => {
// Unsplash prepares each original on request, which can take a minute: fetch the missing ones six at a time
const missing = [...ids].filter(id => !fs.existsSync(path.join(CACHE, id + ".jpg")));
for (let i = 0; i < missing.length; i += 6) await Promise.all(missing.slice(i, i + 6).map(id => fetchMaster(id)));

const list = {};
for (const id of [...ids].sort()) {
  const master = path.join(CACHE, id + ".jpg");
  const dims = run("sips", ["-g", "pixelWidth", "-g", "pixelHeight", master]);
  const W = +dims.match(/pixelWidth: (\d+)/)[1], H = +dims.match(/pixelHeight: (\d+)/)[1];
  const widths = WIDTHS.filter(w => w <= W);
  if (!widths.length) widths.push(W);
  for (const w of widths) {
    const out = path.join(OUT, `${id}-${w}.webp`);
    if (!fs.existsSync(out)) run("cwebp", ["-quiet", "-mt", "-m", "6", "-q", w <= 640 ? "80" : "76", "-resize", String(w), "0", master, "-o", out]);
  }
  // a ~300-byte blurred preview, inlined in data/photos.js so it needs no request of its own
  const tiny = path.join(CACHE, id + "-tiny.webp");
  if (!fs.existsSync(tiny)) run("cwebp", ["-quiet", "-q", "40", "-resize", "24", "0", master, "-o", tiny]);
  list[id] = { w: widths, r: +(H / W).toFixed(4), blur: "data:image/webp;base64," + fs.readFileSync(tiny).toString("base64") };
  if (id === OG) {
    const og = path.join(OUT, `og-${id}.jpg`), tmp = path.join(CACHE, "og-tmp.jpg");
    if (!fs.existsSync(og)) { run("sips", ["--resampleWidth", "1200", master, "--out", tmp]); run("sips", ["--cropToHeightWidth", "630", "1200", tmp, "--out", og]); }
  }
}

// drop files for photos no longer used
const keep = new Set(Object.entries(list).flatMap(([id, p]) => p.w.map(w => `${id}-${w}.webp`)).concat(`og-${OG}.jpg`));
for (const f of fs.readdirSync(OUT)) if (!keep.has(f)) fs.unlinkSync(path.join(OUT, f));

fs.writeFileSync(path.join(ROOT, "data/photos.js"), "/* Generated by tools/build-photos.js: photos served from assets/photos (width list, height/width ratio, blurred preview). */\nwindow.PHOTOS = " + JSON.stringify(list) + ";\n");
const bytes = fs.readdirSync(OUT).reduce((a, f) => a + fs.statSync(path.join(OUT, f)).size, 0);
console.log(`${Object.keys(list).length} photos, ${fs.readdirSync(OUT).length} files, ${(bytes / 1048576).toFixed(1)} MB in assets/photos`);
})().catch(e => { console.error(e.message); process.exit(1); });
