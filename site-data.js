/* Site data layer, shared by the website and the admin panel.
   Content, in order of preference:
     1. a draft saved by the admin in this browser (so they can check changes before publishing)
     2. the live content the admin published to Firestore (site/live, one JSON string)
     3. data/site.js, the copy bundled with the site (used if Firestore is unreachable or empty)
   Public pages read content through Firestore's REST API, without the Firebase SDK. The SDK loads only
   where someone signs in: the admin panel, the account page, and the homepage when a visitor enquires.
   Pages wait for SiteData.ready before reading window.SITE. */
(() => {
  const DRAFT = "wle-site-draft-v1";
  const read = k => { try { return JSON.parse(localStorage.getItem(k)); } catch (e) { return null; } };
  const write = (k, v) => { try { localStorage.setItem(k, JSON.stringify(v)); return true; } catch (e) { return false; } };
  const clone = o => JSON.parse(JSON.stringify(o));
  const CFG = window.FIREBASE_CONFIG || {};
  const REST = `https://firestore.googleapis.com/v1/projects/${CFG.projectId}/databases/(default)/documents`;
  const MAX_DOC = 900 * 1024;                     // Firestore documents top out at 1 MB

  // fill sections added to data/site.js after this copy was saved
  const complete = d => {
    const def = clone(window.SITE_DEFAULT); if (!d || d.version !== def.version) return def;
    for (const k in def) if (!(k in d)) d[k] = def[k];
    const byId = Object.fromEntries((def.packages || []).map(p => [p.id, p]));          // and fields added to packages since
    (d.packages || []).forEach(p => { const base = byId[p.id]; if (base) for (const k in base) if (!(k in p)) p[k] = base[k]; });
    return d;
  };

  /* ---------- IndexedDB for uploaded audio ---------- */
  let dbp;
  const idb = () => dbp || (dbp = new Promise((res, rej) => {
    const r = indexedDB.open("wle-media", 1);
    r.onupgradeneeded = () => r.result.createObjectStore("audio");
    r.onsuccess = () => res(r.result); r.onerror = () => rej(r.error);
  }));
  const idbDo = async (mode, fn) => { const db = await idb(); return new Promise((res, rej) => { const tx = db.transaction("audio", mode); const q = fn(tx.objectStore("audio")); tx.oncomplete = () => res(q && q.result); tx.onerror = () => rej(tx.error); }); };
  const urlCache = {}, itinCache = {};

  /* ---------- live content ---------- */
  let live = null;                                // what visitors see right now (null until fetched or if never published)
  async function fetchLive(ms = 2500) {
    if (!CFG.projectId) return null;
    const ctl = new AbortController(), t = setTimeout(() => ctl.abort(), ms);
    try {
      // the GitHub sync copies each publish into data/site.js (syncedAt) with photos self-hosted; while that copy is
      // current, visitors skip downloading the published one (the admin always reads it)
      const synced = window.SITE_DEFAULT && window.SITE_DEFAULT.syncedAt;
      if (synced && !/admin/.test(location.pathname)) {
        const m = await fetch(`${REST}/site/live?key=${CFG.apiKey}&mask.fieldPaths=updatedAt`, { signal: ctl.signal, cache: "no-store" });
        const at = m.ok ? (((await m.json()).fields || {}).updatedAt || {}).stringValue : null;
        if (!at || at <= synced) return null;
      }
      const r = await fetch(`${REST}/site/live?key=${CFG.apiKey}`, { signal: ctl.signal, cache: "no-store" });
      if (!r.ok) return null;                    // 404 until the first publish
      const doc = await r.json(), json = doc.fields && doc.fields.json && doc.fields.json.stringValue;
      return json ? JSON.parse(json) : null;
    } catch (e) { return null; } finally { clearTimeout(t); }
  }
  const fs = () => { if (!window.firebase || !firebase.firestore) throw new Error("Firebase isn't loaded on this page."); return firebase.firestore(); };

  const SiteData = {
    ready: null,

    /* content */
    get: () => complete(read(DRAFT) || (live && clone(live))),
    published: () => complete(live && clone(live)),
    isLive: () => !!live,
    hasDraft: () => !!read(DRAFT),
    saveDraft(site) { site.updatedAt = new Date().toISOString(); if (!write(DRAFT, site)) throw new Error("This browser's storage is full. Use image links instead of uploads, or remove some uploaded images."); },
    clearDraft() { try { localStorage.removeItem(DRAFT); } catch (e) {} },
    publishedFile(site) { const s = clone(site); delete s.updatedAt; return "/* Published site content. Generated by the admin panel. */\nwindow.SITE_DEFAULT = " + JSON.stringify(s, null, 2) + ";\n"; },
    async publish(site) {                         // admin only: the rules reject anyone else
      const s = clone(site); delete s.updatedAt;
      const json = JSON.stringify(s);
      if (json.length > MAX_DOC) throw new Error(`The content is ${Math.round(json.length / 1024)} KB, over the 900 KB limit. Replace uploaded photos with image links and publish again.`);
      const user = firebase.auth().currentUser;
      await fs().doc("site/live").set({ json, updatedAt: new Date().toISOString(), by: user ? user.email : "" });
      live = s; SiteData.clearDraft();
    },

    /* itineraries: one Firestore document per package (itineraries/{id}), loaded when someone opens that package.
       The client's original itineraries ship as data/itineraries/{id}.json and are used until the admin saves an edit. */
    async itinerary(id) {
      if (id in itinCache) return itinCache[id];
      let doc = null;
      const ctl = new AbortController(), t = setTimeout(() => ctl.abort(), 2500);
      try {
        const r = await fetch(`${REST}/itineraries/${encodeURIComponent(id)}?key=${CFG.apiKey}`, { signal: ctl.signal, cache: "no-store" });
        if (r.ok) { const j = await r.json(), v = j.fields && j.fields.json && j.fields.json.stringValue; if (v) doc = { ...JSON.parse(v), edited: true }; }
      } catch (e) {} finally { clearTimeout(t); }
      if (!doc) { try { const r = await fetch(`data/itineraries/${encodeURIComponent(id)}.json`); if (r.ok) doc = await r.json(); } catch (e) {} }
      return (itinCache[id] = doc);
    },
    async saveItinerary(id, data) {                // admin only
      const clean = { ...data }; delete clean.edited;
      const json = JSON.stringify(clean);
      if (json.length > MAX_DOC) throw new Error("This itinerary is too long to save. Shorten the day descriptions.");
      const user = firebase.auth().currentUser;
      await fs().doc("itineraries/" + id).set({ json, updatedAt: new Date().toISOString(), by: user ? user.email : "" });
      itinCache[id] = { ...clean, edited: true };
    },
    async resetItinerary(id) { await fs().doc("itineraries/" + id).delete(); delete itinCache[id]; },

    /* media */
    // photos listed in data/photos.js are served from assets/photos (tools/build-photos.js); anything else
    // (a photo added in the admin since the last build) still comes from Unsplash
    img(ref, w = 1200) {
      if (!ref) return "";
      const local = window.PHOTOS && window.PHOTOS[ref];
      if (local) { const pw = local.w.find(x => x >= w) || local.w[local.w.length - 1]; return `/assets/photos/${local.f || ref}-${pw}.webp`; }
      if (/^photo-/.test(ref)) return `https://images.unsplash.com/${ref}?w=${w}&q=78&auto=format&fit=crop`;
      return ref; // full URL or data: URL
    },
    srcset(ref, widths = [700, 1200, 1800]) {
      const local = window.PHOTOS && window.PHOTOS[ref];
      if (local) return local.w.map(w => `/assets/photos/${local.f || ref}-${w}.webp ${w}w`).join(", ");
      return /^photo-/.test(ref || "") ? widths.map(w => `${SiteData.img(ref, w)} ${w}w`).join(", ") : "";
    },
    preview(ref) { const local = window.PHOTOS && window.PHOTOS[ref]; return local ? local.blur : ""; },   // tiny blurred version, inline
    async putAudio(key, blob) { await idbDo("readwrite", s => s.put(blob, key)); delete urlCache[key]; return "idb:" + key; },
    async deleteAudio(key) { await idbDo("readwrite", s => s.delete(key)); delete urlCache[key]; },
    async audioURL(ref) {
      if (!ref) return "";
      if (!ref.startsWith("idb:")) return ref;
      const key = ref.slice(4);
      if (urlCache[key]) return urlCache[key];
      const blob = await idbDo("readonly", s => s.get(key));
      return blob ? (urlCache[key] = URL.createObjectURL(blob)) : "";
    },

    /* enquiries (Firestore: enquiries/{id}). Sent by a signed-in customer; admins read them. */
    async addEnquiry(e) {
      const u = window.firebase && firebase.auth && firebase.auth().currentUser;
      if (!u) throw new Error("Sign in to send an enquiry.");
      const item = { trip: "", tripId: "", name: "", phone: "", month: "", travellers: "", from: "", hotel: "", budget: "", message: "", ...e, status: "new", at: new Date().toISOString(), uid: u.uid, email: u.email || "" };
      const ref = await fs().collection("enquiries").add(item);
      return { id: ref.id, ...item };
    },
    async listEnquiries() {
      const snap = await fs().collection("enquiries").orderBy("at", "desc").limit(500).get();
      return snap.docs.map(d => ({ id: d.id, ...d.data() }));
    },
    updateEnquiry: (id, patch) => fs().collection("enquiries").doc(id).update(patch),
  };

  window.SiteData = SiteData;
  window.SITE = SiteData.get();                   // bundled content right away, replaced when ready resolves
  SiteData.ready = fetchLive().then(l => { live = l; window.SITE = SiteData.get(); return window.SITE; });
})();
